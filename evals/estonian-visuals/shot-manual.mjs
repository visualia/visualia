import { chromium } from 'playwright';
const b = await chromium.launch({ channel: 'chrome', args: ['--use-gl=angle'] });
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errs = []; p.on('pageerror', (e) => errs.push(String(e)));
await p.goto('http://127.0.0.1:8123/drift-room/room-splat.html?test&autostart');
await p.waitForFunction(() => window.room?.splats); await p.waitForTimeout(3000);
const cam = () => p.evaluate(() => { const c = room.pose.cam; return { W: +c.W.toFixed(3), x: +c.x.toFixed(3), yaw: +c.yaw.toFixed(2), pitch: +c.pitch.toFixed(2), manual: c.manual, a: room.scene.a }; });
console.log('auto', await cam());
await p.keyboard.down('ArrowUp'); await p.keyboard.down('KeyD'); await p.waitForTimeout(6000);
console.log('held up+right 6 s (should sit near limits)', await cam());
await p.keyboard.up('ArrowUp'); await p.keyboard.up('KeyD');
await p.mouse.move(700, 450); await p.mouse.down(); await p.mouse.move(1100, 450, { steps: 10 }); await p.mouse.up();
console.log('dragged 400 px', await cam()); await p.waitForTimeout(2500);
console.log('2.5 s later (eased back)', await cam());
await p.screenshot({ path: 'out/drift-room/room3d-manual.png' });
await p.waitForTimeout(9000); console.log('after 9 s idle', await cam());
console.log('errors', errs); await b.close();
